//! Mipmaps are only created on request (glium#843).

#[macro_use]
extern crate safegl;

use safegl::texture::{MipmapsOption, RawImage2d, Texture2d, TextureCreationError};

mod support;

#[cfg(target_arch = "wasm32")]
use wasm_bindgen_test::wasm_bindgen_test as test;

fn checkerboard() -> RawImage2d<'static, u8> {
    // a 2x2 image of black and white texels, whose 1x1 mipmap is grey
    RawImage2d::from_raw_rgba(
        vec![0, 0, 0, 255, 255, 255, 255, 255, 255, 255, 255, 255, 0, 0, 0, 255],
        (2, 2),
    )
}

#[test]
fn new_has_no_mipmaps() {
    let display = support::build_display();

    let texture = Texture2d::new(&display, checkerboard()).unwrap();
    assert_eq!(texture.get_mipmap_levels(), 1);

    display.assert_no_error(None);
}

#[test]
fn generated_mipmaps() {
    let display = support::build_display();

    let texture =
        Texture2d::with_mipmaps(&display, checkerboard(), MipmapsOption::AutoGeneratedMipmaps)
            .unwrap();
    assert_eq!(texture.get_mipmap_levels(), 2);

    // the level 1 is the average of the level 0
    let level: Vec<Vec<(u8, u8, u8, u8)>> = texture
        .mipmap(1)
        .unwrap()
        .first_layer()
        .into_image(None)
        .unwrap()
        .raw_read(&safegl::Rect {
            left: 0,
            bottom: 0,
            width: 1,
            height: 1,
        })
        .unwrap();
    let (r, g, b, a) = level[0][0];
    assert!((126..=129).contains(&r) && r == g && g == b && a == 255);

    // they can be generated again, after writing to the main level
    texture.generate_mipmaps().unwrap();

    display.assert_no_error(None);
}

#[cfg(any(safegl_desktop, safegl_gles31))]
#[test]
fn multisample_textures_have_no_mipmaps() {
    let display = support::build_display();

    let texture = match safegl::texture::Texture2dMultisample::empty(&display, 4, 4, 4) {
        Ok(texture) => texture,
        Err(safegl::texture::TextureCreationError::TypeNotSupported)
            | Err(safegl::texture::TextureCreationError::FormatNotSupported) => return,
        Err(e) => panic!("{:?}", e),
    };
    assert_eq!(
        texture.generate_mipmaps(),
        Err(TextureCreationError::MipmapsNotSupported)
    );

    display.assert_no_error(None);
}

#[test]
fn formats_without_mipmaps() {
    let display = support::build_display();
    if !support::is_gles(&display) {
        // desktop OpenGL generates the mipmaps of every format
        return;
    }

    // OpenGL ES only generates the mipmaps of color-renderable and filterable formats
    let data = vec![vec![(0u32, 0u32, 0u32, 0u32); 4]; 4];
    let result = safegl::texture::UnsignedTexture2d::with_mipmaps(
        &display,
        data,
        MipmapsOption::AutoGeneratedMipmaps,
    );
    assert!(matches!(result, Err(TextureCreationError::MipmapsNotSupported)));

    display.assert_no_error(None);
}

/// A texture with fewer levels than down to 1x1 is complete, also without texture storage:
/// sampling its last level reads it, and generating its mipmaps stops there.
#[test]
fn fewer_levels_than_the_full_chain() {
    use safegl::uniforms::{MagnifySamplerFilter, MinifySamplerFilter};
    use safegl::Surface;

    let display = support::build_display();
    let texture = Texture2d::empty_with_mipmaps(&display, MipmapsOption::EmptyMipmapsMax(1), 4, 4)
        .unwrap();
    assert_eq!(texture.get_mipmap_levels(), 2);
    texture.as_surface().clear_color(1.0, 0.0, 0.0, 1.0);
    safegl::framebuffer::SimpleFrameBuffer::new(&display, texture.mipmap(1).unwrap())
        .unwrap()
        .clear_color(0.0, 1.0, 0.0, 1.0);

    // the level of detail of a 1x1 target sampling the 4x4 texture is 2, clamped to the level 1
    let target = Texture2d::empty(&display, 1, 1).unwrap();
    let (vb, ib) = support::build_rectangle_vb_ib(&display);
    let program = support::program_from_legacy(
        &display,
        "#version 110\nattribute vec2 position;\nvarying vec2 uv;\n\
         void main() { uv = position * 0.5 + 0.5; gl_Position = vec4(position, 0.0, 1.0); }",
        "#version 110\nuniform sampler2D tex;\nvarying vec2 uv;\n\
         void main() { gl_FragColor = texture2D(tex, uv); }",
    )
    .unwrap();
    let sampler = texture
        .sampled()
        .minify_filter(MinifySamplerFilter::NearestMipmapNearest)
        .magnify_filter(MagnifySamplerFilter::Nearest);
    target
        .as_surface()
        .draw(
            &vb,
            &ib,
            &program,
            &uniform! { tex: sampler },
            &Default::default(),
        )
        .unwrap();
    let pixels: Vec<Vec<(u8, u8, u8, u8)>> = target.read().unwrap();
    assert_eq!(pixels[0][0], (0, 255, 0, 255));

    display.assert_no_error(None);
}

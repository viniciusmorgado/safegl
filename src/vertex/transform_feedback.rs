/// Transform feedback captures in buffers the vertices generated by the vertex shader, geometry
/// shader, or tessellation evaluation shader of a program, to draw them again or read them.
///
/// A `TransformFeedback` is an OpenGL transform feedback object with the buffers that it
/// captures into, one per buffer of the program (see `Program::get_transform_feedback_buffers`):
/// one per varying in separate mode, and one per group of varyings that `gl_NextBuffer` or the
/// `xfb_buffer` qualifier separates in interleaved mode. It mutably borrows the buffers. Each
/// draw given it in its parameters appends its vertices after those of the previous ones; a
/// draw or a dispatch without it pauses the capture, which the next draw with it resumes.
/// `finish` ends the capture and gives the number of captured vertices, which
/// `glDrawTransformFeedback` draws.
///
/// # Notes
///
/// - The program must capture varyings, given when building it or with `xfb_*` qualifiers.
///   Every draw with the object must use this program and the same type of primitives: points,
///   lines or triangles, whatever the strips, fans and adjacency of the draws.
///
/// - The buffers aren't necessarily filled: a `TransformFeedbackPrimitivesWrittenQuery` counts the
///   captured primitives. Capturing stops for a vertex stream once one of its buffers is full.
///
/// - The buffer receives lists of points, lines (two vertices) or triangles (three vertices):
///   drawing strips or fans duplicates vertices.
///
/// # Example
///
/// ```no_run
/// # use safegl::{implement_vertex, uniform};
/// # use safegl::Surface;
/// # use glutin::surface::{ResizeableSurface, SurfaceTypeTrait};
/// # fn example<T>(display: safegl::Display<T>, program: safegl::Program,
/// #            vb: safegl::vertex::VertexBufferAny, ib: safegl::index::IndexBuffer<u16>)
/// #     where T: SurfaceTypeTrait + ResizeableSurface {
/// #[derive(Copy, Clone, Debug, PartialEq)]
/// struct Vertex {
///     output_val: (f32, f32),
/// }
///
/// implement_vertex!(Vertex, output_val);
/// safegl::implement_any_bit_pattern!(Vertex, output_val);
///
/// let mut out_buffer: safegl::VertexBuffer<Vertex> = safegl::VertexBuffer::empty(&display, 6).unwrap();
///
/// {
///     let transform_feedback = safegl::vertex::TransformFeedback::new(&display, &program)
///         .unwrap()
///         .with_buffer(&mut out_buffer)
///         .unwrap();
///
///     let params = safegl::DrawParameters {
///         transform_feedback: Some(&transform_feedback),
///         .. Default::default()
///     };
///
///     display.draw().draw(&vb, &ib, &program, &uniform!{}, &params).unwrap();
/// }
///
/// let result: Vec<Vertex> = out_buffer.read().unwrap();
/// println!("List of generated vertices: {:?}", result);
/// # }
/// ```
pub struct TransformFeedback<'a> {
    context: Rc<Context>,
    program: &'a Program,
    // the buffers, by binding index (a `Vec` keeps the struct covariant)
    buffers: Vec<BufferAnySlice<'a>>,
    // the number of vertices that each buffer holds
    capacities: SmallVec<[usize; 4]>,
    // the transform feedback object, and the generation of the context that created it
    object: Cell<Option<(glow::TransformFeedback, u64)>>,
}

/// Error that can happen when building a `TransformFeedback`.
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub enum TransformFeedbackCreationError {
    /// The program doesn't capture any varying.
    NothingCaptured,

    /// The program captures into fewer buffers than given.
    TooManyBuffers,

    /// The format of the vertices of the buffer doesn't match the varyings that the program
    /// captures into it.
    WrongVertexFormat,

    /// The program or the buffer belongs to another context. OpenGL objects can only be used
    /// with the context that created them.
    ContextMismatch,
}

impl fmt::Display for TransformFeedbackCreationError {
    fn fmt(&self, fmt: &mut fmt::Formatter<'_>) -> fmt::Result {
        use self::TransformFeedbackCreationError::*;
        let desc = match *self {
            NothingCaptured => "The program doesn't capture any varying",
            TooManyBuffers => "The program captures into fewer buffers than given",
            WrongVertexFormat => {
                "The format of the output doesn't match what the program is expected to output"
            }
            ContextMismatch => "The program or the buffer belongs to another context",
        };
        fmt.write_str(desc)
    }
}

impl Error for TransformFeedbackCreationError {}

impl<'a> TransformFeedback<'a> {
    /// Builds a transform feedback object that captures the varyings of `program`, without
    /// buffers yet: give it the buffers of the program in order with `with_buffer`. For a
    /// program pipeline, the varyings are the ones of the program of the last stage before
    /// rasterization.
    pub fn new<F: ?Sized>(
        facade: &F,
        program: impl Into<crate::program::DrawProgram<'a>>,
    ) -> Result<TransformFeedback<'a>, TransformFeedbackCreationError>
    where
        F: Facade,
    {
        let program = program.into().last_vertex_stage();
        // OpenGL objects can only be used with the context that created them
        let context = facade.get_context();
        if !std::ptr::eq(ProgramExt::get_context(program), &**context) {
            return Err(TransformFeedbackCreationError::ContextMismatch);
        }
        if program.get_transform_feedback_buffers().is_empty() {
            return Err(TransformFeedbackCreationError::NothingCaptured);
        }

        Ok(TransformFeedback {
            context: context.clone(),
            program,
            buffers: Vec::new(),
            capacities: SmallVec::new(),
            object: Cell::new(None),
        })
    }

    /// Adds the buffer that the next buffer of the program captures into, whose vertices must
    /// have the format of the varyings of this buffer of the program.
    pub fn with_buffer<V>(
        mut self,
        buffer: &'a mut Buffer<[V]>,
    ) -> Result<TransformFeedback<'a>, TransformFeedbackCreationError>
    where
        V: Vertex + Copy + Send + 'static,
    {
        if !Rc::ptr_eq(buffer.get_context(), &self.context) {
            return Err(TransformFeedbackCreationError::ContextMismatch);
        }

        let index = self.buffers.len();
        let program_buffer = self
            .program
            .get_transform_feedback_buffers()
            .iter()
            .find(|program_buffer| program_buffer.id == index as i32)
            .ok_or(TransformFeedbackCreationError::TooManyBuffers)?;
        let bindings = <V as Vertex>::build_bindings();
        let matches = program_buffer.stride == mem::size_of::<V>()
            && program_buffer.elements.iter().all(|element| {
                bindings.iter().any(|binding| {
                    binding.1 == element.offset && binding.3 == element.ty
                }) && !bindings
                    .iter()
                    .any(|binding| binding.1 != element.offset && binding.0 == element.name)
            });
        if !matches {
            return Err(TransformFeedbackCreationError::WrongVertexFormat);
        }

        self.capacities.push(buffer.len());
        self.buffers.push(buffer.as_slice_any());
        Ok(self)
    }

    /// Ends the capture, and returns the captured vertices, which can be drawn without knowing
    /// their number (`glDrawTransformFeedback`). The buffers aren't borrowed anymore.
    pub fn finish(self) -> CapturedVertices {
        let mut ctxt = self.context.make_current();
        let generation = ctxt.context.generation();
        let object = self
            .object
            .get()
            .filter(|&(_, object_generation)| object_generation == generation);
        let recorded = object.is_some_and(|(id, _)| unsafe { end(&mut ctxt, id) });
        let capacity = self.capacities.iter().copied().max().unwrap_or(0);
        drop(ctxt);

        // the object goes to the captured vertices, which delete it
        self.object.set(None);
        CapturedVertices {
            context: self.context.clone(),
            object,
            recorded,
            capacity,
        }
    }
}

impl<'a> TransformFeedbackExt for TransformFeedback<'a> {
    #[inline]
    fn get_context(&self) -> &Rc<Context> {
        &self.context
    }

    #[inline]
    fn get_program_id(&self) -> glow::Program {
        self.program.get_id()
    }

    fn is_recording(&self, ctxt: &CommandContext<'_>) -> bool {
        let generation = ctxt.context.generation();
        self.object.get().is_some_and(|(id, object_generation)| {
            object_generation == generation
                && ctxt
                    .state
                    .transform_feedbacks
                    .iter()
                    .any(|recording| recording.id == id && !recording.paused)
        })
    }

    fn bind(
        &self,
        ctxt: &mut CommandContext<'_>,
        draw_primitives: PrimitiveType,
    ) -> Result<(), DrawError> {
        if self.buffers.len() != self.program.get_transform_feedback_buffers().len() {
            return Err(DrawError::TransformFeedbackBuffersMissing);
        }

        let primitives = match (self.program.get_output_primitives(), draw_primitives) {
            (Some(OutputPrimitives::Points), _) => gl::POINTS,
            (Some(OutputPrimitives::Lines), _) => gl::LINES,
            (Some(OutputPrimitives::Triangles), _) => gl::TRIANGLES,
            // tessellating a `quads` domain outputs triangles
            (Some(OutputPrimitives::Quads), _) => gl::TRIANGLES,
            (None, PrimitiveType::Points) => gl::POINTS,
            (None, PrimitiveType::LinesList) => gl::LINES,
            #[cfg(any(safegl_desktop, safegl_gles32))]
            (None, PrimitiveType::LinesListAdjacency) => gl::LINES,
            (None, PrimitiveType::LineStrip) => gl::LINES,
            #[cfg(any(safegl_desktop, safegl_gles32))]
            (None, PrimitiveType::LineStripAdjacency) => gl::LINES,
            (None, PrimitiveType::LineLoop) => gl::LINES,
            (None, PrimitiveType::TrianglesList) => gl::TRIANGLES,
            #[cfg(any(safegl_desktop, safegl_gles32))]
            (None, PrimitiveType::TrianglesListAdjacency) => gl::TRIANGLES,
            (None, PrimitiveType::TriangleStrip) => gl::TRIANGLES,
            #[cfg(any(safegl_desktop, safegl_gles32))]
            (None, PrimitiveType::TriangleStripAdjacency) => gl::TRIANGLES,
            (None, PrimitiveType::TriangleFan) => gl::TRIANGLES,
            #[cfg(any(safegl_desktop, safegl_gles32))]
            (None, PrimitiveType::Patches { .. }) => unreachable!(),
        };

        // a capture can't change its type of primitives
        let id = self.object(ctxt);
        if let Some(recording) = ctxt.state.transform_feedbacks.iter().find(|r| r.id == id) {
            if recording.primitives != primitives {
                return Err(DrawError::TransformFeedbackPrimitivesMismatch);
            }
        }

        unsafe {
            TransformFeedback::pause(ctxt);
            bind_object(ctxt, Some(id));
            match ctxt
                .state
                .transform_feedbacks
                .iter_mut()
                .find(|recording| recording.id == id)
            {
                Some(recording) => {
                    ctxt.glow.resume_transform_feedback();
                    recording.paused = false;
                }
                None => {
                    ctxt.glow.begin_transform_feedback(primitives);
                    ctxt.state.transform_feedbacks.push(crate::context::RecordingTransformFeedback {
                        id,
                        primitives,
                        paused: false,
                        buffers: self.buffers.iter().map(|buffer| buffer.get_id()).collect(),
                    });
                }
            }
        }
        Ok(())
    }

    fn pause(ctxt: &mut CommandContext<'_>) {
        let recording = ctxt
            .state
            .transform_feedbacks
            .iter()
            .position(|recording| !recording.paused);
        if let Some(position) = recording {
            let id = ctxt.state.transform_feedbacks[position].id;
            unsafe {
                bind_object(ctxt, Some(id));
                ctxt.glow.pause_transform_feedback();
            }
            ctxt.state.transform_feedbacks[position].paused = true;
        }
    }

    fn ensure_buffer_out_of_transform_feedback(
        ctxt: &mut CommandContext<'_>,
        buffer: glow::Buffer,
    ) {
        // only the capture that isn't paused writes to its buffers
        let writing = ctxt
            .state
            .transform_feedbacks
            .iter()
            .any(|recording| !recording.paused && recording.buffers.contains(&buffer));
        if writing {
            TransformFeedback::pause(ctxt);
        }
    }
}

impl<'a> TransformFeedback<'a> {
    /// Returns the transform feedback object, which is created with its buffers the first time,
    /// and again in a new context after `Context::rebuild`: transform feedback objects aren't
    /// shared between contexts.
    fn object(&self, ctxt: &mut CommandContext<'_>) -> glow::TransformFeedback {
        let generation = ctxt.context.generation();
        if let Some((id, object_generation)) = self.object.get() {
            if object_generation == generation {
                return id;
            }
        }

        unsafe {
            TransformFeedback::pause(ctxt);
            let id = ctxt
                .glow
                .create_transform_feedback()
                .expect("glGenTransformFeedbacks failed");
            bind_object(ctxt, Some(id));
            for (index, buffer) in self.buffers.iter().enumerate() {
                buffer.bind_to_transform_feedback(ctxt, index as gl::types::GLuint);
            }
            self.object.set(Some((id, generation)));
            id
        }
    }
}

impl<'a> Drop for TransformFeedback<'a> {
    fn drop(&mut self) {
        let mut ctxt = self.context.make_current();
        if let Some((id, generation)) = self.object.get() {
            if generation == ctxt.context.generation() {
                unsafe {
                    end(&mut ctxt, id);
                    delete_object(&mut ctxt, id);
                }
            }
        }
    }
}

/// The vertices that a `TransformFeedback` captured, which `glDrawTransformFeedback` draws from
/// the buffers given as vertex sources, without reading back their number: see
/// `CapturedVertices::indices`.
pub struct CapturedVertices {
    context: Rc<Context>,
    // the transform feedback object, and the generation of the context that created it
    object: Option<(glow::TransformFeedback, u64)>,
    // whether anything was captured: an object that never began has no number of vertices
    recorded: bool,
    // the most vertices that a vertex stream captured, the size of the largest buffer
    capacity: usize,
}

impl CapturedVertices {
    /// Builds an indices source that draws the vertices captured for the vertex stream 0, as
    /// `primitives`, from the vertex sources of the draw (`glDrawTransformFeedback`), which must
    /// have as many vertices as the largest buffer of the capture.
    #[cfg(safegl_desktop)]
    #[cfg_attr(docsrs, doc(cfg(safegl_desktop)))]
    #[inline]
    pub fn indices(&self, primitives: PrimitiveType) -> crate::index::IndicesSource<'_> {
        self.stream_indices(0, primitives)
    }

    /// Like `indices`, for the vertices captured for another vertex stream of a geometry shader,
    /// below `Limits::max_vertex_streams` (`glDrawTransformFeedbackStream`).
    #[cfg(safegl_desktop)]
    #[cfg_attr(docsrs, doc(cfg(safegl_desktop)))]
    #[inline]
    pub fn stream_indices(
        &self,
        stream: u32,
        primitives: PrimitiveType,
    ) -> crate::index::IndicesSource<'_> {
        crate::index::IndicesSource::TransformFeedback {
            captured: self,
            stream,
            primitives,
        }
    }

    /// Returns the context of the capture.
    #[inline]
    pub(crate) fn get_context(&self) -> &Rc<Context> {
        &self.context
    }

    /// Returns the object to draw from, `Ok(None)` if nothing was captured, or an error if the
    /// context was rebuilt since the capture, which lost it.
    pub(crate) fn object(
        &self,
        ctxt: &CommandContext<'_>,
    ) -> Result<Option<glow::TransformFeedback>, DrawError> {
        match self.object {
            Some((id, generation)) if generation == ctxt.context.generation() => {
                Ok(if self.recorded { Some(id) } else { None })
            }
            Some(_) => Err(DrawError::CapturedVerticesLost),
            None if self.recorded => Err(DrawError::CapturedVerticesLost),
            None => Ok(None),
        }
    }

    /// Returns the most vertices that the capture holds.
    #[inline]
    pub(crate) fn capacity(&self) -> usize {
        self.capacity
    }
}

impl Drop for CapturedVertices {
    fn drop(&mut self) {
        let mut ctxt = self.context.make_current();
        if let Some((id, generation)) = self.object {
            if generation == ctxt.context.generation() {
                unsafe { delete_object(&mut ctxt, id) };
            }
        }
    }
}

impl fmt::Debug for TransformFeedback<'_> {
    fn fmt(&self, fmt: &mut fmt::Formatter<'_>) -> fmt::Result {
        fmt.debug_struct("TransformFeedback")
            .field("object", &self.object.get())
            .field("capacities", &self.capacities)
            .finish()
    }
}

impl fmt::Debug for CapturedVertices {
    fn fmt(&self, fmt: &mut fmt::Formatter<'_>) -> fmt::Result {
        fmt.debug_struct("CapturedVertices")
            .field("object", &self.object)
            .field("recorded", &self.recorded)
            .field("capacity", &self.capacity)
            .finish()
    }
}

/// Binds a transform feedback object, `None` for the default one.
unsafe fn bind_object(ctxt: &mut CommandContext<'_>, id: Option<glow::TransformFeedback>) {
    if ctxt.state.transform_feedback != id {
        ctxt.glow.bind_transform_feedback(glow::TRANSFORM_FEEDBACK, id);
        ctxt.state.transform_feedback = id;
    }
}

/// Ends the capture of an object if it is recording, and returns whether it was.
unsafe fn end(ctxt: &mut CommandContext<'_>, id: glow::TransformFeedback) -> bool {
    let position = match ctxt
        .state
        .transform_feedbacks
        .iter()
        .position(|recording| recording.id == id)
    {
        Some(position) => position,
        None => return false,
    };

    // binding another object needs the recording one to be paused
    if ctxt.state.transform_feedback != Some(id) {
        TransformFeedback::pause(ctxt);
        bind_object(ctxt, Some(id));
    }
    ctxt.glow.end_transform_feedback();
    ctxt.state.transform_feedbacks.remove(position);
    true
}

/// Deletes an object that doesn't record, which binds the default object if it was bound.
unsafe fn delete_object(ctxt: &mut CommandContext<'_>, id: glow::TransformFeedback) {
    ctxt.glow.delete_transform_feedback(id);
    if ctxt.state.transform_feedback == Some(id) {
        ctxt.state.transform_feedback = None;
    }
}

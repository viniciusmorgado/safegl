/// Describes the source to use for the vertices when drawing.
#[derive(Clone)]
pub enum VerticesSource<'a> {
    /// A buffer uploaded in the video memory.
    ///
    /// The second parameter is the format of its vertices, and the third one how often its
    /// attributes advance: per vertex, or per instance.
    VertexBuffer(BufferAnySlice<'a>, VertexFormat, InstanceRate),

    /// A value for an attribute of every vertex, which no buffer provides.
    Constant(ConstantAttribute<'a>),

    /// A marker indicating a "phantom list of attributes".
    Marker {
        /// Number of attributes.
        len: usize,

        /// Whether or not this buffer is "per instance" (true) or "per vertex" (false).
        per_instance: bool,
    },
}

/// Marker that can be passed instead of a buffer to indicate an empty list of buffers.
pub struct EmptyVertexAttributes {
    /// Number of phantom vertices.
    pub len: usize,
}

impl<'a> From<EmptyVertexAttributes> for VerticesSource<'a> {
    #[inline]
    fn from(this: EmptyVertexAttributes) -> VerticesSource<'a> {
        VerticesSource::Marker {
            len: this.len,
            per_instance: false,
        }
    }
}

/// Marker that can be passed instead of a buffer to indicate an empty list of buffers.
pub struct EmptyInstanceAttributes {
    /// Number of phantom vertices.
    pub len: usize,
}

impl<'a> From<EmptyInstanceAttributes> for VerticesSource<'a> {
    #[inline]
    fn from(this: EmptyInstanceAttributes) -> VerticesSource<'a> {
        VerticesSource::Marker {
            len: this.len,
            per_instance: true,
        }
    }
}

/// The same value for an attribute of every vertex and instance (`glVertexAttrib*`), passed
/// among the vertex sources of a draw instead of a buffer:
///
/// ```no_run
/// # use glutin::surface::{ResizeableSurface, SurfaceTypeTrait};
/// # fn example<T>(display: safegl::Display<T>, vertices: safegl::vertex::VertexBufferAny,
/// #     program: safegl::Program) where T: SurfaceTypeTrait + ResizeableSurface {
/// use safegl::Surface;
/// use safegl::vertex::ConstantAttribute;
///
/// let color = ConstantAttribute::new("color", [1.0f32, 0.0, 0.0, 1.0]);
/// let mut frame = display.draw();
/// frame
///     .draw(
///         (&vertices, color),
///         safegl::index::NoIndices(safegl::index::PrimitiveType::TrianglesList),
///         &program,
///         &safegl::uniforms::EmptyUniforms,
///         &Default::default(),
///     )
///     .unwrap();
/// frame.finish().unwrap();
/// # }
/// ```
///
/// The value must have the type of the attribute, otherwise the draw returns
/// `DrawError::AttributeTypeMismatch`, and no buffer of the draw may provide the attribute too
/// (`DrawError::AttributeProvidedTwice`). A program without the attribute ignores it.
#[derive(Copy, Clone, Debug, PartialEq)]
pub struct ConstantAttribute<'a> {
    name: &'a str,
    value: AttributeValue,
}

impl<'a> ConstantAttribute<'a> {
    /// The value `value` for the attribute named `name`.
    #[inline]
    pub fn new(name: &'a str, value: impl Into<AttributeValue>) -> ConstantAttribute<'a> {
        ConstantAttribute {
            name,
            value: value.into(),
        }
    }

    /// Returns the name of the attribute.
    #[inline]
    pub fn name(&self) -> &'a str {
        self.name
    }

    /// Returns the value.
    #[inline]
    pub fn value(&self) -> AttributeValue {
        self.value
    }
}

impl<'a> From<ConstantAttribute<'a>> for VerticesSource<'a> {
    #[inline]
    fn from(this: ConstantAttribute<'a>) -> VerticesSource<'a> {
        VerticesSource::Constant(this)
    }
}

/// The value of a constant attribute: one to four floats, signed or unsigned integers, or
/// doubles, built from a value or an array of up to four of them. The components that the value
/// doesn't give are 0, and 1 for the fourth one.
#[derive(Copy, Clone, Debug, PartialEq)]
pub enum AttributeValue {
    /// `float` to `vec4` attributes (`glVertexAttrib4f`).
    Float([f32; 4], u8),
    /// `int` to `ivec4` attributes (`glVertexAttribI4i`).
    Int([i32; 4], u8),
    /// `uint` to `uvec4` attributes (`glVertexAttribI4ui`).
    UnsignedInt([u32; 4], u8),
    /// `double` to `dvec4` attributes (`glVertexAttribL4d`), which need OpenGL 4.1 or
    /// `GL_ARB_vertex_attrib_64bit`.
    #[cfg(safegl_gl41)]
    #[cfg_attr(docsrs, doc(cfg(safegl_gl41)))]
    Double([f64; 4], u8),
}

impl AttributeValue {
    /// Returns the type of the attribute that the value is for.
    pub fn attribute_type(&self) -> AttributeType {
        use self::AttributeType::*;

        let types = match *self {
            AttributeValue::Float(_, _) => [F32, F32F32, F32F32F32, F32F32F32F32],
            AttributeValue::Int(_, _) => [I32, I32I32, I32I32I32, I32I32I32I32],
            AttributeValue::UnsignedInt(_, _) => [U32, U32U32, U32U32U32, U32U32U32U32],
            #[cfg(safegl_gl41)]
            AttributeValue::Double(_, _) => [F64, F64F64, F64F64F64, F64F64F64F64],
        };
        let components = match *self {
            AttributeValue::Float(_, n)
            | AttributeValue::Int(_, n)
            | AttributeValue::UnsignedInt(_, n) => n,
            #[cfg(safegl_gl41)]
            AttributeValue::Double(_, n) => n,
        };
        types[components as usize - 1]
    }
}

macro_rules! attribute_value {
    ($variant:ident, $ty:ty, $zero:expr, $one:expr) => {
        impl From<$ty> for AttributeValue {
            #[inline]
            fn from(value: $ty) -> AttributeValue {
                AttributeValue::$variant([value, $zero, $zero, $one], 1)
            }
        }

        impl From<[$ty; 2]> for AttributeValue {
            #[inline]
            fn from(value: [$ty; 2]) -> AttributeValue {
                AttributeValue::$variant([value[0], value[1], $zero, $one], 2)
            }
        }

        impl From<[$ty; 3]> for AttributeValue {
            #[inline]
            fn from(value: [$ty; 3]) -> AttributeValue {
                AttributeValue::$variant([value[0], value[1], value[2], $one], 3)
            }
        }

        impl From<[$ty; 4]> for AttributeValue {
            #[inline]
            fn from(value: [$ty; 4]) -> AttributeValue {
                AttributeValue::$variant(value, 4)
            }
        }
    };
}

attribute_value!(Float, f32, 0.0, 1.0);
attribute_value!(Int, i32, 0, 1);
attribute_value!(UnsignedInt, u32, 0, 1);
#[cfg(safegl_gl41)]
attribute_value!(Double, f64, 0.0, 1.0);

/// How often the attributes of a vertex source advance.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash)]
pub enum InstanceRate {
    /// Once per vertex.
    PerVertex,

    /// Once every this many instances (`glVertexAttribDivisor`): a buffer of `n` elements
    /// provides the attributes of `n` times this many instances.
    PerInstance(NonZeroU32),
}

/// Marker that instructs SafeGL that the buffer is to be used per instance.
pub struct PerInstance<'a>(BufferAnySlice<'a>, VertexFormat, NonZeroU32);

impl<'a> PerInstance<'a> {
    /// Builds the marker from a slice and its format, for one element per instance.
    pub(crate) fn new(slice: BufferAnySlice<'a>, format: VertexFormat) -> PerInstance<'a> {
        PerInstance(slice, format, NonZeroU32::MIN)
    }

    /// Makes each element of the buffer provide the attributes of `divisor` consecutive
    /// instances, instead of one.
    #[inline]
    pub fn with_divisor(self, divisor: NonZeroU32) -> PerInstance<'a> {
        PerInstance(self.0, self.1, divisor)
    }
}

impl<'a> From<PerInstance<'a>> for VerticesSource<'a> {
    #[inline]
    fn from(this: PerInstance<'a>) -> VerticesSource<'a> {
        VerticesSource::VertexBuffer(this.0, this.1, InstanceRate::PerInstance(this.2))
    }
}

/// Objects that describe multiple vertex sources.
pub trait MultiVerticesSource<'a> {
    /// Iterator that enumerates each source.
    type Iterator: Iterator<Item = VerticesSource<'a>>;

    /// Iterates over the `VerticesSource`.
    fn iter(self) -> Self::Iterator;
}

impl<'a, T> MultiVerticesSource<'a> for T
where
    T: Into<VerticesSource<'a>>,
{
    type Iterator = IntoIter<VerticesSource<'a>>;

    #[inline]
    fn iter(self) -> IntoIter<VerticesSource<'a>> {
        Some(self.into()).into_iter()
    }
}

macro_rules! impl_for_tuple {
    ($t:ident) => (
        impl<'a, $t> MultiVerticesSource<'a> for ($t,)
            where $t: Into<VerticesSource<'a>>
        {
            type Iterator = IntoIter<VerticesSource<'a>>;

            #[inline]
            fn iter(self) -> IntoIter<VerticesSource<'a>> {
                Some(self.0.into()).into_iter()
            }
        }
    );

    ($t1:ident, $t2:ident) => (
        #[allow(non_snake_case)]
        impl<'a, $t1, $t2> MultiVerticesSource<'a> for ($t1, $t2)
            where $t1: Into<VerticesSource<'a>>, $t2: Into<VerticesSource<'a>>
        {
            type Iterator = Chain<<($t1,) as MultiVerticesSource<'a>>::Iterator,
                                  <($t2,) as MultiVerticesSource<'a>>::Iterator>;

            #[inline]
            fn iter(self) -> Chain<<($t1,) as MultiVerticesSource<'a>>::Iterator,
                                   <($t2,) as MultiVerticesSource<'a>>::Iterator>
            {
                let ($t1, $t2) = self;
                Some($t1.into()).into_iter().chain(($t2,).iter())
            }
        }

        impl_for_tuple!($t2);
    );

    ($t1:ident, $($t2:ident),+) => (
        #[allow(non_snake_case)]
        impl<'a, $t1, $($t2),+> MultiVerticesSource<'a> for ($t1, $($t2),+)
            where $t1: Into<VerticesSource<'a>>, $($t2: Into<VerticesSource<'a>>),+
        {
            type Iterator = Chain<<($t1,) as MultiVerticesSource<'a>>::Iterator,
                                  <($($t2),+) as MultiVerticesSource<'a>>::Iterator>;

            #[inline]
            fn iter(self) -> Chain<<($t1,) as MultiVerticesSource<'a>>::Iterator,
                                  <($($t2),+) as MultiVerticesSource<'a>>::Iterator>
            {
                let ($t1, $($t2),+) = self;
                Some($t1.into()).into_iter().chain(($($t2),+).iter())
            }
        }

        impl_for_tuple!($($t2),+);
    );
}

impl_for_tuple!(A, B, C, D, E, F, G);

/// Trait for structures that represent a vertex.
///
/// Instead of implementing this trait yourself, it is recommended to use the `implement_vertex!`
/// macro instead.
///
/// # Safety
///
/// The `VertexFormat` returned by `build_bindings` must describe the layout of the type: the
/// offset and type of each attribute must match a field, so that the GPU doesn't read outside of
/// the vertices.
pub unsafe trait Vertex: Copy + Sized {
    /// Builds the `VertexFormat` representing the layout of this element.
    fn build_bindings() -> VertexFormat;

    /// Returns true if the backend supports this vertex format.
    fn is_supported<C: ?Sized>(caps: &C) -> bool
    where
        C: CapabilitiesSource,
    {
        let format = Self::build_bindings();

        for &(_, _, _, ref ty, _) in format.iter() {
            if !ty.is_supported(caps) {
                return false;
            }
        }

        true
    }
}

/// Trait for types that can be used as vertex attributes.
pub unsafe trait Attribute: Sized {
    /// The type of data.
    const TYPE: AttributeType;

    #[inline]
    /// Get the type of data.
    fn get_type() -> AttributeType {
        Self::TYPE
    }

    /// Returns true if the backend supports this type of attribute.
    #[inline]
    fn is_supported<C: ?Sized>(caps: &C) -> bool
    where
        C: CapabilitiesSource,
    {
        Self::get_type().is_supported(caps)
    }
}
